// ─── Helpers ────────────────────────────────────────────────────────
function mttLookup(dict, key) {
  return key.split('.').reduce((obj, part) => (obj != null && obj[part] !== undefined ? obj[part] : undefined), dict);
}

function mttReadStoredLang() {
  try {
    const stored = localStorage.getItem(MTT_LANG_KEY);
    if (stored === 'vi' || stored === 'en') return stored;
  } catch (e) { /* storage unavailable — default to Vietnamese */ }
  return 'vi';
}

function mttTranslate(lang, key, vars) {
  let value = mttLookup(I18N[lang], key);
  if (value === undefined) value = mttLookup(I18N.vi, key); // fall back to Vietnamese
  if (value === undefined) return key;                       // never show a blank label
  if (vars && typeof value === 'string') {
    Object.keys(vars).forEach(name => {
      value = value.split('{' + name + '}').join(String(vars[name]));
    });
  }
  return value;
}

// ─── Context / provider / hook ──────────────────────────────────────
const LanguageContext = createContextI18n(null);

function LanguageProvider({ children }) {
  const [lang, setLangState] = useStateI18n(mttReadStoredLang);

  const setLang = (next) => {
    if (next !== 'vi' && next !== 'en') return;
    setLangState(next);
    try { localStorage.setItem(MTT_LANG_KEY, next); } catch (e) { /* ignore */ }
    document.documentElement.lang = next;
  };

  const t = (key, vars) => mttTranslate(lang, key, vars);

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

// Safe outside a provider too (returns Vietnamese defaults).
function useI18n() {
  const ctx = useContextI18n(LanguageContext);
  if (ctx) return ctx;
  return { lang: 'vi', setLang: () => {}, t: (key, vars) => mttTranslate('vi', key, vars) };
}

document.documentElement.lang = mttReadStoredLang();

Object.assign(window, { I18N, LanguageContext, LanguageProvider, useI18n });
